package general_java;

public class if_else_ladder {

    public static void main(String[] args) {

        int marks = 89;
        if (marks >= 90) {
            System.out.println("offier");
        } else if (marks >= 80) {
            System.out.println("clerk");
        } else if (marks >= 70) {
            System.out.println("pune");
        } else {
            System.out.println("not qualified");
        }

    }

}
