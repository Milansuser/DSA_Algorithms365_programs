package general_java;

public class int_divi_float {

    public static void main(String[] args) {

        int a = 7;
        int b = 2;

        System.out.println("int divide: " + a / b);

        float c = 7f;
        float d = 2f;

        System.out.println("float divide: " + c / d);


        double e = 7;
        double f = 2;

        System.out.println("double divide: " + (e / f));
        
        System.out.println("f" + ((float) (a) / b));
        //System.err.println()
        
        // any one is double or float then the ans will be float or double



    }

}
